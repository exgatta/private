# -*- coding: utf-8 -*-
"""古代神殿の宝物回廊 — レッドストーン式ピットフォールトラップ。

苔むした石レンガの回廊の奥に、グロウストーンが輝く宝の祭壇。
祭壇の手前の敷石(石の感圧板)を踏むと、床下のレッドストーントーチが消え、
左右にかくした粘着ピストン4台が床を引きぬいて、感圧板の前後2列の床が同時に開く。
踏んだ人は深さ7マスの縦穴へ——底はガラスごしに溶岩が光る安全な「溶岩観察室」。
感圧板は動かない橋の上にあるので、罠は自動で閉じて何度でも使える。

罠の手前(z=7)の左右端(x=2とx=5)には装飾柱を立てて通路を中央レーン(x=3..4)に
絞ってある。端のレーンは引きぬいた床がピストンのアームごと駐機する場所なので、
柱で通れなくすることで「どこを歩いても必ず落ちる」ことを保証する。

座標: x=0..7(西→東=図の左→右), z=0(北=祭壇)..z=10(南=入口), y=0が最下段。
サイズ: 8×11マス・高さ12段(地下8段+地上4段)、約270ブロック。
"""

from blueprint import VoxelModel


def build():
    m = VoxelModel(
        "古代神殿の宝物回廊トラップ",
        "光る宝で誘いこむ石レンガの回廊。祭壇手前の感圧板を踏むと"
        "粘着ピストン4台が床を引きぬき、深さ7マスの縦穴へ落とす。"
        "手前の装飾柱で通路を中央2マスに絞ってあるので、よけて通る道はない。"
        "底はガラスで密封した溶岩の間。罠は自動復帰式。8×11マス・高さ12段。",
    )

    # ================= 地下部 (y=0..7) =================
    # --- y=0(1段目): 溶岩の間の底。石の外枠の中に溶岩をためる ---
    m.fill(2, 0, 3, 5, 0, 7, "stone")
    m.fill(3, 0, 4, 4, 0, 6, "lava")

    # --- y=1(2段目): 溶岩のふた。落ちた人が着地するガラス床 ---
    m.fill(2, 1, 3, 5, 1, 7, "stone")
    m.fill(3, 1, 4, 4, 1, 6, "glass")

    # --- y=2..5(3〜6段目): 縦穴(シャフト)の壁 ---
    for y in (2, 3, 4, 5):
        m.hollow_box(2, y, 3, 5, y, 7, "stone_bricks")
    # 底の部屋の明かり: 壁の内側の面にグロウストーンを埋めこむ
    m.set(2, 2, 4, "glowstone")
    m.set(5, 2, 6, "glowstone")
    m.set(3, 2, 3, "glowstone")
    m.set(4, 2, 7, "glowstone")
    # 古びた雰囲気の苔
    m.set(2, 4, 5, "mossy_stone_bricks")
    m.set(5, 3, 4, "mossy_stone_bricks")

    # --- y=6(7段目): シャフト壁 + 橋の下のダスト受け台 ---
    m.hollow_box(2, 6, 3, 5, 6, 7, "stone_bricks")
    m.set(3, 6, 5, "stone")   # ダストを支える台
    m.set(4, 6, 5, "stone")

    # --- y=7(8段目): 回路層(罠の心臓部)。外から見えないよう石で包む ---
    m.fill(0, 7, 3, 7, 7, 7, "stone")
    # 落下する2列(z=4とz=6)の真下は空けておく(落下の通り道)
    for z in (4, 6):
        m.set(3, 7, z, None)
        m.set(4, 7, z, None)
    # 橋の真下にレッドストーンダストを東西一直線に(信号の通り道)
    for x in (2, 3, 4, 5):
        m.set(x, 7, 5, "redstone_wire")
    # レッドストーントーチ4本: (1,7,5)と(6,7,5)の石の北面・南面に横付け
    m.set(1, 7, 4, "redstone_torch")
    m.set(1, 7, 6, "redstone_torch")
    m.set(6, 7, 4, "redstone_torch")
    m.set(6, 7, 6, "redstone_torch")

    # ================= 床レベル (y=8, 9段目) =================
    # 南側: 入口(z=10)から罠の手前までの回廊の床
    m.fill(1, 8, 7, 6, 8, 10, "stone_bricks")
    # 北側: 祭壇の土台
    m.fill(1, 8, 0, 6, 8, 3, "stone_bricks")
    # 罠ゾーン: z=4とz=6が「落とし床」の列
    for z in (4, 6):
        m.set(1, 8, z, "sticky_piston")   # 東向き(図の右向き)に設置
        m.set(6, 8, z, "sticky_piston")   # 西向き(図の左向き)に設置
        m.set(3, 8, z, "stone_bricks")    # ピストンが保持する落とし床
        m.set(4, 8, z, "stone_bricks")
        # (2,8,z)と(5,8,z)は空欄のまま: 伸びたピストンのアームが埋まる場所
    # z=5: 動かない「橋」。この上に感圧板が乗る
    m.fill(2, 8, 5, 5, 8, 5, "stone_bricks")
    m.set(1, 8, 5, "stone")
    m.set(6, 8, 5, "stone")
    # 床の苔の演出(古い神殿感)
    m.set(2, 8, 8, "mossy_stone_bricks")
    m.set(4, 8, 9, "mossy_stone_bricks")
    m.set(5, 8, 7, "mossy_stone_bricks")
    m.set(3, 8, 10, "mossy_stone_bricks")

    # 9段目のレイヤー図に注記: 空欄4マスはアームの駐機場所
    m.layer_notes[8] = (
        "図で空欄になっている4マス (x=2,z=4)(x=5,z=4)(x=2,z=6)(x=5,z=6) は、"
        "伸びた粘着ピストンのアームが埋まる場所。ここには何も置かないこと！"
        "うっかりブロックを置くとピストンが伸びられず罠が動かなくなる。"
    )

    # ================= 地上部 (y=9..11, 10〜12段目) =================
    # --- y=9: 回廊の壁・感圧板・祭壇 ---
    m.fill(1, 9, 0, 1, 9, 10, "stone_bricks")   # 西の壁
    m.fill(6, 9, 0, 6, 9, 10, "stone_bricks")   # 東の壁
    m.set(1, 9, 2, "mossy_stone_bricks")
    m.set(1, 9, 6, "mossy_stone_bricks")
    m.set(6, 9, 4, "mossy_stone_bricks")
    m.set(6, 9, 9, "mossy_stone_bricks")
    # 端レーン対策の装飾柱: 罠の手前(z=7)のx=2とx=5をふさぎ、
    # 通行を中央レーン(x=3..4)に絞る。端のレーン(x=2, x=5)は
    # 引きぬいた床ブロックが駐機する列なので、歩かせると落ちないため。
    m.set(2, 9, 7, "chiseled_stone_bricks")
    m.set(5, 9, 7, "chiseled_stone_bricks")
    # 罠のスイッチ: 橋の上に石の感圧板4枚(通路の幅いっぱい・よけられない)
    m.fill(2, 9, 5, 5, 9, 5, "stone_pressure_plate")
    # 祭壇: 一段高い台(z=1..2)と背面の壁(z=0)
    m.fill(2, 9, 1, 5, 9, 2, "stone_bricks")
    m.set(2, 9, 2, "chiseled_stone_bricks")
    m.set(5, 9, 2, "chiseled_stone_bricks")
    m.fill(1, 9, 0, 6, 9, 0, "stone_bricks")

    # --- y=10: 祭壇の飾り壁・宝の台座・門柱・装飾柱の上段・たいまつ ---
    m.fill(1, 10, 0, 6, 10, 0, "stone_bricks")
    m.set(2, 10, 0, "glowstone")               # 祭壇をてらす明かり
    m.set(5, 10, 0, "glowstone")
    m.set(3, 10, 0, "chiseled_stone_bricks")
    m.set(4, 10, 0, "chiseled_stone_bricks")
    m.set(3, 10, 1, "chiseled_stone_bricks")   # 宝の台座
    m.set(4, 10, 1, "chiseled_stone_bricks")
    m.set(2, 10, 7, "chiseled_stone_bricks")   # 装飾柱の上段(飛びこえ防止)
    m.set(5, 10, 7, "chiseled_stone_bricks")
    m.set(1, 10, 10, "stone_bricks")           # 入口の門柱
    m.set(6, 10, 10, "stone_bricks")
    m.set(1, 10, 7, "torch")                   # 壁の上のたいまつ
    m.set(6, 10, 7, "torch")

    # --- y=11: 背面壁の上段・光る宝・入口アーチ ---
    m.fill(1, 11, 0, 6, 11, 0, "stone_bricks")
    m.set(3, 11, 1, "glowstone")               # ★光る宝(入口からまっすぐ見えるエサ)
    m.set(4, 11, 1, "glowstone")
    m.set(1, 11, 10, "chiseled_stone_bricks")  # 門柱の頭
    m.set(6, 11, 10, "chiseled_stone_bricks")
    m.fill(2, 11, 10, 5, 11, 10, "stone_bricks")  # 入口の上のアーチ

    m.notes = [
        "地下(1〜8段目)は地面に深さ8マスの穴(横8×奥行き5マス)を掘って埋めこむと、"
        "地上には神殿の回廊だけが見えて完璧にカモフラージュできる。",
        "レッドストーン部品の組立順はこの順番を必ず守る: "
        "【1】レッドストーントーチ4本 → 【2】粘着ピストン4台 → "
        "【3】アームの先の床石レンガ4個 → 【4】最後に石の感圧板4枚。"
        "トーチより先にピストンを置くとアームが縮んだままになり、"
        "床石レンガを置く位置をまちがえやすいので注意。",
        "【1】8段目(y=7)が回路の心臓部。レッドストーントーチ4本は床置きではなく『横付け』: "
        "西側2本は石ブロック(x=1,z=5)の北面と南面に、東側2本は石ブロック(x=6,z=5)の"
        "北面と南面に貼り付ける(トーチの下が空洞でもOK)。",
        "同じ8段目、橋の真下(x=2〜5, z=5)にレッドストーンダストを東西一直線に4つ敷く。"
        "線の両端がトーチ付きの石(x=1とx=6)に向いて、踏んだときにトーチを消す役になる。",
        "【2】9段目(y=8)の粘着ピストン4台は向きが命: 西側の2台(x=1, z=4とz=6)は東向き"
        "(図の右向き)、東側の2台(x=6, z=4とz=6)は西向き(図の左向き)。真下のトーチの力で"
        "『置いたとたんアームが伸びる』のが正解。逆向きでアームが伸びない台があったら、"
        "壊して反対側から置き直す。",
        "【3】伸びたアームの先(x=3とx=4, z=4とz=6)に石レンガを1個ずつ置くと落とし床が完成。"
        "図で空欄のマス(x=2とx=5, z=4とz=6)はアームが埋めるので絶対に何も置かない。",
        "【4】石の感圧板4枚(x=2〜5, z=5)は一番最後に置く。踏むと『橋の石→真下のダスト→"
        "トーチ消灯→ピストン後退』と信号が伝わり、感圧板の前後2列の床が同時に開く。"
        "石の感圧板は足を離れても約0.5〜1秒ほどONが続くうえ、前後2列が同時に開くので、"
        "前に進んでも後ろに逃げても穴に落ちる。"
        "感圧板は動かない橋の上にあるから、罠は自動で閉じて何度でも使える。",
        "10段目(y=9)の装飾柱2本(x=2とx=5, z=7。11段目まで積む)は飾りではなく仕掛けの一部: "
        "端のレーン(x=2とx=5)は引きぬいた床が駐機して落ちない通路になるため、"
        "柱でふさいで侵入者を必ず中央レーン(x=3〜4)に歩かせる。省略しないこと。",
        "溶岩は最下段(y=0)だけで、上を全面ガラス(y=1)でふさいであるので落ちた人は燃えない。"
        "落下は7マスでダメージはハート2個ほど。底に閉じこめられた人は外から掘って救出する。",
        "祭壇の光る宝(グロウストーン)は入口からまっすぐ見える高さに置いてある。"
        "誘われて回廊を進むと、宝の3マス手前で足元が消える——という演出。",
    ]
    return m
