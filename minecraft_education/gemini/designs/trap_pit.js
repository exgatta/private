S(3, 6, 5, "stone");
S(4, 6, 5, "stone");

// --- y=7(8段目): 回路層(罠の心臓部) ---
F(0, 7, 3, 7, 7, 7, "stone");
[4, 6].forEach(function (z) { C(3, 7, z); C(4, 7, z); });
[2, 3, 4, 5].forEach(function (x) { S(x, 7, 5, "redstone_wire"); });
S(1, 7, 4, "redstone_torch");
